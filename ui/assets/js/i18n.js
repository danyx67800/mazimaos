let current = "it";
const dicts = { en, it };
export function setLanguage(lang) { current = lang === "en" ? "en" : "it"; document.documentElement.lang = current; }
export function getLanguage() { return current; }
export function t(key, vars = {}) {
  let value = dicts[current]?.[key] ?? en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v));
  return value;
}
export function errorText(err) {
  if (!err) return t("toast.error");
  if (err.code && en[`error.${err.code}`]) return t(`error.${err.code}`);
  if (err.status === 0) return t("error.network");
  return err.message || t("toast.error");
}
export function locale() { return current === "it" ? "it-IT" : "en-US"; }
