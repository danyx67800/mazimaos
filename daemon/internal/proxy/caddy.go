package proxy

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"time"

	"github.com/danyx67800/mazimaos/daemon/internal/dockerstore"
)

type Caddy struct {
	mu           sync.Mutex
	AppsDir      string
	Snippet      string
	AliasSnippet string
	MainConfig   string
	Enabled      bool
	Reload       func(ctx context.Context) error
	Now          func() time.Time
}

var aliasRE = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$`)

func NewCaddy(appsDir, snippet, mainConfig string) *Caddy {
	c := &Caddy{
		AppsDir:      appsDir,
		Snippet:      snippet,
		AliasSnippet: filepath.Join(filepath.Dir(snippet), "apps-aliases.caddy"),
		MainConfig:   mainConfig,
		Enabled:      true,
		Now:          time.Now,
	}
	_ = c.writeSnippet(c.Snippet, "# Generated by mazimad. Do not edit by hand.\n")
	_ = c.writeSnippet(c.AliasSnippet, "# Generated by mazimad. Do not edit by hand.\n")
	c.Reload = func(ctx context.Context) error {
		if _, err := exec.LookPath("caddy"); err != nil {
			return errors.New("caddy binary not found")
		}
		cmd := exec.CommandContext(ctx, "caddy", "reload", "--config", mainConfig, "--adapter", "caddyfile")
		out, err := cmd.CombinedOutput()
		if err != nil {
			return fmt.Errorf("caddy reload: %w: %s", err, strings.TrimSpace(string(out)))
		}
		return nil
	}
	return c
}

func (c *Caddy) ApplyApp(app dockerstore.Manifest) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.regenerateLocked()
}

func (c *Caddy) RemoveApp(id string) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.regenerateLocked()
}

func (c *Caddy) ListRoutes() ([]string, error) {
	apps, err := c.apps()
	if err != nil {
		return nil, err
	}
	var out []string
	for _, a := range apps {
		if a.Proxy.Mode == "alias" {
			out = append(out, "https://"+a.Proxy.Hostname+"/")
		} else {
			out = append(out, "/apps/"+a.ID+"/")
		}
	}
	return out, nil
}

func (c *Caddy) apps() ([]dockerstore.Manifest, error) {
	entries, err := os.ReadDir(c.AppsDir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	var out []dockerstore.Manifest
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		man, err := dockerstore.LoadInstalledManifest(filepath.Join(c.AppsDir, e.Name()))
		if err != nil {
			continue
		}
		if _, err := os.Stat(filepath.Join(c.AppsDir, e.Name(), ".removed")); err == nil {
			continue
		}
		out = append(out, *man)
	}
	return out, nil
}

func (c *Caddy) writeSnippet(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".apps-*.caddy")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}

func (c *Caddy) regenerateLocked() error {
	apps, err := c.apps()
	if err != nil {
		return err
	}
	var routes, aliases strings.Builder
	routes.WriteString("# Generated by mazimad. Do not edit by hand.\n")
	routes.WriteString("# Path routes are imported inside the main site.\n\n")
	aliases.WriteString("# Generated by mazimad. Do not edit by hand.\n")
	aliases.WriteString("# Alias routes are imported at the top level.\n\n")
	for _, app := range apps {
		port := app.HostPort
		if port == 0 {
			continue
		}
		switch app.Proxy.Mode {
		case "alias":
			host := strings.ToLower(strings.TrimSpace(app.Proxy.Hostname))
			if !aliasRE.MatchString(host) {
				continue
			}
			fmt.Fprintf(&aliases, "https://%s {\n", host)
			aliases.WriteString("\ttls internal\n")
			aliases.WriteString("\theader_down -X-Frame-Options\n")
			aliases.WriteString("\theader {\n")
			aliases.WriteString("\t\tX-Content-Type-Options nosniff\n")
			aliases.WriteString("\t\tReferrer-Policy strict-origin-when-cross-origin\n")
			aliases.WriteString("\t}\n")
			fmt.Fprintf(&aliases, "\treverse_proxy 127.0.0.1:%d\n", port)
			aliases.WriteString("}\n\n")
		case "path":
			if !strings.HasPrefix(app.Proxy.BasePath, "/") && app.Proxy.BasePath != "" {
				continue
			}
			fmt.Fprintf(&routes, "handle_path /apps/%s/* {\n", app.ID)
			routes.WriteString("\theader {\n")
			routes.WriteString("\t\tX-Content-Type-Options nosniff\n")
			routes.WriteString("\t}\n")
			fmt.Fprintf(&routes, "\treverse_proxy 127.0.0.1:%d\n", port)
			routes.WriteString("}\n\n")
		}
	}
	if err := c.writeSnippet(c.Snippet, routes.String()); err != nil {
		return err
	}
	if err := c.writeSnippet(c.AliasSnippet, aliases.String()); err != nil {
		return err
	}
	if !c.Enabled {
		return nil
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	if err := c.Reload(ctx); err != nil {
		return err
	}
	return nil
}
